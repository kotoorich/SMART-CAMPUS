import { useCallback, useEffect, useRef, useState } from "react";
import { Html5Qrcode } from "html5-qrcode";
import {
  Camera, CheckCircle2, ImageUp, MapPin, QrCode, RefreshCw, RotateCcw, ShieldCheck, UserCheck,
} from "lucide-react";
import MainLayout from "../../layouts/MainLayout";
import { markAttendance, getMyAttendance } from "../../services/api";
import { getBestPosition } from "../../utils/geo";

// Resize a captured frame into a compact JPEG so the selfie payload stays small.
function captureFrame(video, maxWidth = 480) {
  const scale = Math.min(1, maxWidth / (video.videoWidth || maxWidth));
  const canvas = document.createElement("canvas");
  canvas.width = Math.round((video.videoWidth || maxWidth) * scale);
  canvas.height = Math.round((video.videoHeight || maxWidth) * scale);
  canvas.getContext("2d").drawImage(video, 0, 0, canvas.width, canvas.height);
  return canvas.toDataURL("image/jpeg", 0.75);
}

function fileToDataUrl(file) {
  return new Promise((resolve, reject) => {
    const reader = new FileReader();
    reader.onload = () => resolve(reader.result);
    reader.onerror = () => reject(new Error("We could not read that image. Try another photo."));
    reader.readAsDataURL(file);
  });
}

function decodePayload(raw) {
  let parsed;
  try { parsed = JSON.parse(raw); }
  catch { throw new Error("This image does not contain a valid Smart Campus attendance QR code."); }
  const token = parsed.token;
  if (!token) throw new Error("The QR code is incomplete or is not an attendance QR generated by your lecturer.");
  return { token };
}

export default function StudentAttendance() {
  const [mode, setMode] = useState("idle");     // idle | camera | selfie | verifying | success | error
  const [message, setMessage] = useState("");
  const [error, setError] = useState("");
  const [result, setResult] = useState(null);
  const [token, setToken] = useState("");
  const [accessCode, setAccessCode] = useState("");
  const [manualCode, setManualCode] = useState("");
  const [selfie, setSelfie] = useState("");
  const [busy, setBusy] = useState(false);
  const [summary, setSummary] = useState(null);
  const fileRef = useRef(null);
  const selfieInputRef = useRef(null);
  const videoRef = useRef(null);
  const streamRef = useRef(null);

  const loadSummary = useCallback(() => {
    getMyAttendance().then(setSummary).catch(() => {});
  }, []);
  useEffect(() => { loadSummary(); }, [loadSummary]);

  const stopCamera = useCallback(() => {
    if (streamRef.current) {
      streamRef.current.getTracks().forEach(t => t.stop());
      streamRef.current = null;
    }
  }, []);

  const submitAttendance = useCallback(async (credential, image) => {
    setBusy(true); setError(""); setMessage("Requesting your current location…");
    try {
      const pos = await getBestPosition();
      setMessage("Checking the attendance session, selfie submission and classroom location…");
      const data = await markAttendance({
        ...credential, image,
        latitude: pos.latitude, longitude: pos.longitude, accuracy: pos.accuracy,
      });
      setResult(data); setMessage(data.message || "Attendance recorded."); setMode("success"); loadSummary();
    } catch (e) {
      setError(e.message); setMode("error");
    } finally { setBusy(false); }
  }, [loadSummary]);

  // Live camera for QR scanning.
  useEffect(() => {
    if (mode !== "camera") return;
    let live = true;
    const scanner = new Html5Qrcode("student-qr-reader");
    scanner.start({ facingMode: "environment" }, { fps: 10, qrbox: { width: 240, height: 240 } }, text => {
      if (!live) return; live = false;
      scanner.stop().catch(() => {}).finally(() => scanner.clear().catch(() => {}));
      try { const payload = decodePayload(text); setToken(payload.token); setAccessCode(""); setMode("selfie"); }
      catch (e) { setError(e.message); setMode("error"); }
    }, () => {}).catch(e => {
      if (live) { setError(e?.message || "Camera could not start. Check browser camera permission or upload the QR image instead."); setMode("error"); }
    });
    return () => { live = false; scanner.stop().catch(() => {}).finally(() => scanner.clear().catch(() => {})); };
  }, [mode]);

  // Front camera for the selfie.
  useEffect(() => {
    if (mode !== "selfie") { stopCamera(); return; }
    let live = true;
    navigator.mediaDevices?.getUserMedia({ video: { facingMode: "user" }, audio: false })
      .then(stream => {
        if (!live) { stream.getTracks().forEach(t => t.stop()); return; }
        streamRef.current = stream;
        if (videoRef.current) { videoRef.current.srcObject = stream; videoRef.current.play().catch(() => {}); }
      })
      .catch(() => { /* fall back to file upload */ });
    return () => { live = false; stopCamera(); };
  }, [mode, stopCamera]);

  const uploadQr = async file => {
    if (!file) return;
    setBusy(true); setError(""); setMessage("Reading the QR code from your image…");
    try {
      const reader = new Html5Qrcode("student-qr-file-reader");
      let decoded; try { decoded = await reader.scanFile(file, true); } finally { reader.clear().catch(() => {}); }
      const payload = decodePayload(decoded); setToken(payload.token); setAccessCode(""); setMode("selfie");
    } catch (e) { setError(e.message || "Unable to read this QR image. Upload a clear, uncropped image."); setMode("error"); }
    finally { setBusy(false); }
  };

  const takeSelfie = () => {
    const video = videoRef.current;
    if (!video || !video.videoWidth) { setError("The camera is not ready yet. Wait a moment or upload a selfie instead."); return; }
    const dataUrl = captureFrame(video);
    setSelfie(dataUrl); stopCamera();
    submitAttendance(accessCode ? { access_code: accessCode } : { token }, dataUrl);
  };

  const uploadSelfie = async file => {
    if (!file) return;
    try { const dataUrl = await fileToDataUrl(file); setSelfie(dataUrl); submitAttendance(accessCode ? { access_code: accessCode } : { token }, dataUrl); }
    catch (e) { setError(e.message); setMode("error"); }
  };

  const useManualCode = (e) => {
    e.preventDefault();
    const code = manualCode.trim().toUpperCase();
    if (code.length < 6) { setError("Enter the attendance code displayed by your lecturer."); return; }
    setError(""); setToken(""); setAccessCode(code); setMode("selfie");
  };

  const reset = () => {
    stopCamera();
    setMode("idle"); setMessage(""); setError(""); setResult(null); setSelfie(""); setToken(""); setAccessCode(""); setManualCode(""); setBusy(false);
    if (fileRef.current) fileRef.current.value = "";
    if (selfieInputRef.current) selfieInputRef.current.value = "";
  };

  const records = summary?.records || [];
  const overall = summary?.overall;

  return <MainLayout>
    <main className="attendance-qr-page">
      <header className="attendance-qr-heading">
        <span className="attendance-kicker">STUDENT / ATTENDANCE</span>
        <h1>Mark your attendance</h1>
        <p>Scan your lecturer’s live QR code, then take a selfie. Your current location is verified to confirm you are in class.</p>
      </header>

      {mode === "success" ? <section className="attendance-result success">
        <div className="attendance-result-icon"><CheckCircle2 size={30}/></div>
        <h2>You're checked in.</h2>
        <p>{message}</p>
        <div className="attendance-result-grid">
          <span>Student<strong>{result?.student_name || "Your account"}</strong></span>
          <span>Index number<strong>{result?.index_number || "—"}</strong></span>
          <span>Course<strong>{result?.course_code || "—"}</strong></span>
          <span>Date<strong>{result?.date || "—"}</strong></span>
          <span>Distance<strong>{result?.distance_meters ?? "—"} m</strong></span>
          <span>Method<strong>{result?.method || "QR + selfie + location"}</strong></span>
        </div>
        <button className="attendance-primary" onClick={reset}>Done <CheckCircle2 size={17}/></button>
      </section> : <section className="attendance-qr-card">
        <div className="attendance-qr-card-top">
          <span className="attendance-qr-symbol"><QrCode size={22}/></span>
          <div><h2>Verify class attendance</h2><p>Use the live QR code or the short attendance code displayed by your lecturer.</p></div>
          <span className="attendance-secure"><ShieldCheck size={14}/> Secure</span>
        </div>

        {mode === "camera" && <div className="attendance-camera-wrap">
          <div id="student-qr-reader"/>
          <p>Hold the lecturer’s QR code inside the frame.</p>
          <button className="attendance-secondary" onClick={() => setMode("idle")}>Cancel camera</button>
        </div>}

        {mode === "selfie" && <div className="attendance-selfie-wrap">
          <p className="attendance-selfie-hint"><UserCheck size={16}/> Capture a clear selfie to attach to this attendance record.</p>
          <video ref={videoRef} playsInline muted className="attendance-selfie-video"/>
          {selfie && <img src={selfie} alt="Your selfie preview" className="attendance-selfie-preview"/>}
          <div className="attendance-selfie-actions">
            <button className="attendance-primary" onClick={takeSelfie} disabled={busy}><Camera size={16}/> Capture selfie</button>
            <button className="attendance-secondary" onClick={() => selfieInputRef.current?.click()} disabled={busy}><ImageUp size={16}/> Upload selfie</button>
            <button className="attendance-secondary" onClick={() => setMode("idle")} disabled={busy}>Cancel</button>
          </div>
          <input ref={selfieInputRef} type="file" accept="image/*" capture="user" hidden onChange={e => uploadSelfie(e.target.files?.[0])}/>
        </div>}

        {(busy || mode === "verifying") && <div className="attendance-progress">
          <span className="attendance-spinner"/>
          <div><strong>{message || "Verifying attendance…"}</strong><small>Please keep location services enabled.</small></div>
        </div>}

        {error && <div className="attendance-error" role="alert">{error}</div>}
        {mode === "error" && <button className="attendance-secondary retry" onClick={reset}><RotateCcw size={16}/> Try again</button>}

        {mode === "idle" && <form className="attendance-manual-code attendance-manual-code-prominent" onSubmit={useManualCode}>
          <label htmlFor="attendance-code">Have an attendance code? Enter it here</label>
          <div><input id="attendance-code" value={manualCode} onChange={e=>setManualCode(e.target.value.toUpperCase())} placeholder="Enter the code from your lecturer" autoCapitalize="characters" maxLength={16} autoComplete="off"/><button className="attendance-primary" type="submit">Continue</button></div>
        </form>}
        {mode === "idle" && <div className="attendance-methods">
          <button className="attendance-method" onClick={() => { setError(""); setMode("camera"); }}>
            <span><Camera size={22}/></span><strong>Scan with camera</strong><small>Use your phone or laptop camera</small>
          </button>
          <button className="attendance-method" onClick={() => fileRef.current?.click()}>
            <span><ImageUp size={22}/></span><strong>Upload QR image</strong><small>Select a photo or screenshot of the code</small>
          </button>
          <input ref={fileRef} type="file" accept="image/*" hidden onChange={e => uploadQr(e.target.files?.[0])}/>
        </div>}
        <div id="student-qr-file-reader" className="qr-file-reader-hidden"/>

        <div className="attendance-location-note">
          <MapPin size={17}/>
          <span><strong>QR code, selfie and location are all required</strong>
          <small>Attendance is accepted only when your GPS position is within the classroom’s permitted radius.</small></span>
        </div>
      </section>}

      {overall && <section className="attendance-history">
        <div className="attendance-history-head">
          <h2>Your attendance</h2>
          <button className="attendance-secondary" onClick={loadSummary}><RefreshCw size={15}/> Refresh</button>
        </div>
        <div className="attendance-history-summary">
          <span><strong>{overall.rate}%</strong><small>Overall attendance</small></span>
          <span><strong>{overall.present}</strong><small>Classes attended</small></span>
          <span><strong>{overall.total}</strong><small>Classes held</small></span>
        </div>
        {records.length === 0
          ? <p className="attendance-empty">No attendance recorded yet. Check in to your first class to see it here.</p>
          : <div className="attendance-table-wrap"><table className="attendance-table">
              <thead><tr><th>Date</th><th>Course</th><th>Period</th><th>Status</th><th>Method</th></tr></thead>
              <tbody>{records.slice(0, 20).map(r => <tr key={r.id}>
                <td>{r.date}</td><td>{r.course_code || "—"}</td><td>{r.period}</td>
                <td><span className={`pill ${r.status}`}>{r.status}</span></td><td>{r.method}</td>
              </tr>)}</tbody>
            </table></div>}
      </section>}
    </main>
  </MainLayout>;
}
